#[cfg(test)]
mod tests {
    use hyperion_testkit::float::assert_same_bits;

    use super::*;

    fn assert_symmetric(nodes: &[f64], weights: &[f64]) {
        let n = nodes.len();
        assert_eq!(weights.len(), n);
        for i in 0..n {
            assert_same_bits(nodes[i], -nodes[n - 1 - i]);
            assert_same_bits(weights[i], weights[n - 1 - i]);
            assert!(weights[i] > 0.0);
            if i > 0 {
                assert!(nodes[i] > nodes[i - 1], "nodes ascend");
            }
        }
    }

    #[test]
    fn tables_are_ascending_and_exactly_symmetric() {
        assert_symmetric(&GL4_NODES, &GL4_WEIGHTS);
        assert_symmetric(&GL8_NODES, &GL8_WEIGHTS);
        assert_symmetric(&GL16_NODES, &GL16_WEIGHTS);
        assert_symmetric(&GL32_NODES, &GL32_WEIGHTS);
        assert_symmetric(&GL64_NODES, &GL64_WEIGHTS);
    }

    #[test]
    fn weights_sum_to_two() {
        for weights in [
            &GL4_WEIGHTS[..],
            &GL8_WEIGHTS[..],
            &GL16_WEIGHTS[..],
            &GL32_WEIGHTS[..],
            &GL64_WEIGHTS[..],
        ] {
            let sum: f64 = weights.iter().sum();
            assert!((sum - 2.0).abs() < 4.0 * f64::EPSILON, "sum = {sum}");
        }
    }

    /// Each node is a root of its Legendre polynomial, evaluated by the three-term recurrence. The
    /// tolerance allows for the rounding of the node itself times the slope of P₃₂ or P₆₄ near
    /// ±1, which is some hundreds or thousands.
    #[test]
    fn nodes_are_roots_of_the_legendre_polynomial() {
        fn legendre(n: u32, x: f64) -> f64 {
            let (mut p0, mut p1) = (1.0, x);
            for k in 2..=n {
                let k = f64::from(k);
                (p0, p1) = (p1, ((2.0 * k - 1.0) * x * p1 - (k - 1.0) * p0) / k);
            }
            p1
        }
        for &x in &GL4_NODES {
            assert!(legendre(4, x).abs() < 1e-15, "P4({x})");
        }
        for &x in &GL8_NODES {
            assert!(legendre(8, x).abs() < 1e-15, "P8({x})");
        }
        for &x in &GL16_NODES {
            assert!(legendre(16, x).abs() < 1e-12, "P16({x})");
        }
        for &x in &GL32_NODES {
            assert!(legendre(32, x).abs() < 1e-12, "P32({x})");
        }
        for &x in &GL64_NODES {
            assert!(legendre(64, x).abs() < 1e-12, "P64({x})");
        }
    }
}
