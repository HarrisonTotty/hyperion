//! Gauss–Legendre nodes and weights on `[−1, 1]`, 4, 8, 16, 32 and 64 points.
//!
//! An n-point rule integrates every polynomial of degree up to 2n − 1 exactly. The nodes are the
//! roots of the Legendre polynomial Pₙ and the weights `2 ÷ ((1 − x²) Pₙ′(x)²)` (Abramowitz and
//! Stegun 1964, §25.4.29, whose Table 25.4 prints the values; the same rule is DLMF §3.5(v), eq.
//! 3.5.21, which is the citation to follow, the 1964 handbook being out of print and its scans
//! gone). Each literal is the correctly rounded `f64` of the value computed at 50
//! significant digits with `mpmath` by Newton iteration on Pₙ (the 64-point rule's, P14.T48.a's,
//! at 80 digits in Python's `decimal`), and prints as the shortest decimal that round-trips. Nodes
//! ascend from −1 to +1, and the tables are exactly symmetric: node `i` is the negation of node
//! `n − 1 − i`, and the two weights are equal.
//!
//! The order of the entries is part of the generator version, because the quadratures in
//! [`galaxy::quad`](crate::galaxy::quad) sum in index order.

