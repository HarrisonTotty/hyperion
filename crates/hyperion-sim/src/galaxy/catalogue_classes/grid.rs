//! The catalogue-class grid (plan 09, P09.T32): the machinery every class under the `111` prefix
//! sits on.
//!
//! The brainstorm's "Rare events are found by carving out their hosts, not the events": "By the
//! marking theorem, the systems whose marks put them in a class are an independent Poisson
//! process, which can be placed on its own coarse grid where distant charts and alerts can find
//! it, while the cells draw conditional on not being in the class." This module is that grid, for
//! any class:
//!
//! - [`ClassProcess`], the trait a class implements: its [`ClassId`], a bound over a cell, a
//!   candidate draw under the bound and the class's test (P09.T33.a's core collapses, P09.T34.a's
//!   Type Ia, P09.T43's luminous blue variables and plan 11's five binary classes);
//! - [`CatalogueClassCell`], one class's cell, generated by thinning as plan 03 places the grid
//!   (brainstorm, "Exact placement by thinning");
//! - [`resolve_entry`] and [`resolve`], from a `111` ID to the entry and member it names, or to
//!   "no such system", recomputing one bound, one count and one candidate and never the cell;
//! - [`cells_in_sphere`], the cells of a class whose entries can lie in a sphere at any time the
//!   class serves;
//! - [`check_class_headroom`], which a class's task calls to show that no cell of the class can
//!   draw more candidates than the 24-bit index numbers.
//!
//! **No class is registered** (P09.T32): the production lookup, [`ProductionClasses`], has no
//! process, so every `111` ID that reaches the grid answers
//! [`NoSuchSystem`](ResolveSystemError::NoSuchSystem) and no generated output moves. The task that
//! builds each class's process adds its arm there. Plan 03's
//! [`placement::resolve`](crate::galaxy::placement::resolve) still answers
//! [`KindNotGenerated`](ResolveSystemError::KindNotGenerated) for a `111` ID: P09.T33.a, which
//! registers the first class, wires its dispatch here and adds the record's origin.
//!
//! # Streams
//!
//! A cell's candidate count is one Poisson draw on `class.cell` ([`tags::CLASS_CELL`]), keyed by
//! `ObjectKey::cell(CatalogueCellKey::word())`, the ID of the cell's candidate 0 with its index
//! and member zeroed (Design note 23), of mean the class's bound × the cell's volume. Every class
//! shares the tag: classes share no cell, and the word carries the class. A candidate's draws are
//! its class's own, on `System` tags under `class.` keyed by `ObjectKey::from(SystemId)` of its
//! member 0, so that no class and no candidate shares a stream with another.
//!
//! # Static dispatch
//!
//! An entry's type differs by class (P09.T33.a's carries `SystemStars`, P09.T34.a's an
//! `IaProgenitor` and a survivor), so [`ClassProcess`] has associated types, and the cell, the
//! resolve and the headroom check are generic over the process. A dispatch on [`ClassId`] goes
//! through a [`ClassLookup`], whose one `match` hands the class's process to a [`ClassVisitor`]
//! (as `FeatureCatalogue`'s `count_tag` matches on `FeatureProcess`); [`resolve`] hands what it
//! resolved to a [`MemberVisitor`]. Nothing here is `dyn`: the merge of P09.T37 visits each class
//! in turn and needs no common entry type until it turns entries into records.

