/// A catalogue class's process: what the grid needs to place the class's entries by thinning
/// (plan 09, P09.T32).
///
/// The grid evaluates [`bound`](Self::bound) once per cell, draws the cell's candidate count from
/// it, and hands each candidate's ID and the same bound to [`candidate`](Self::candidate), and a
/// candidate it accepts to [`test`](Self::test): an entry is a candidate both keep. Resolving an ID
/// runs the same three on its one candidate, which is why the resolve reproduces the cell bit for
/// bit (plan 03's `resolve_candidate_with`).
///
/// # The contract
///
/// Every implementation keeps these rules, and the task that builds it shows that it does.
///
/// 1. **Purity.** Each method is a pure function of the galaxy and its arguments. Nothing is
///    cached on first use; values precomputed when the process is built, from the galaxy alone,
///    are allowed. So a cell and a resolve give the same bits whatever was generated before.
/// 2. **Streams.** A candidate draws on `System` tags under `class.`, one per property group,
///    opened with `ObjectKey::from(SystemId::from(id))` of its member 0 (Design note 23), and never
///    on the cell's count stream, `class.cell`.
/// 3. **The bound.** [`bound`](Self::bound) is finite and non-negative, and at least the density of
///    the class's candidates at every point of the cell's closed box;
///    [`candidate`](Self::candidate) accepts on density ÷ bound, through
///    [`Threshold::from_ratio`], whose debug assertion catches a density above it (brainstorm,
///    "Exact placement by thinning").
/// 4. **The test.** [`test`](Self::test) is a deterministic test on the candidate's own marks, the
///    one the grid side (P09.T35) evaluates identically on its own candidate, so that nothing is
///    counted twice. A candidate that fails it is thinned like any other.
/// 5. **The reach.** An entry, with every member of it, stays within [`LIFETIME_REACH`], 4,096 ly,
///    of its cell at every time the lookup serves, because [`cells_in_sphere`] pads a sphere by
///    that and no more (the brainstorm's "the entry's lifetime is held to 4,096 ly ÷ its fastest
///    member's speed, so that lookups stay within a known number of rings of cells"). The
///    supernova classes keep it through [`lifetime_cap`]; every other class shows it in its own
///    task.
/// 6. **One velocity.** Each kind of candidate takes its velocity from one function: a class
///    candidate's is drawn once, by one function, and carried into its test and its entry, never
///    redrawn or rebuilt elsewhere; the grid side's is plan 08's `epoch_velocity` of its record.
///    The velocity handed to [`DeathMarks::of`] as its `velocity` argument (or to
///    [`DeathMarks::of_type_ia`]) decides `W_eff`'s lifetime cap, so two sides that passed the
///    same system different velocities could disagree near the interval's start (P09.T17's
///    deferred findings, "One velocity on every side"). Where two routes cannot be avoided, a test
///    shows that they give the same bits.
/// 7. **Headroom.** No cell of the class may draw more than 2²⁴ candidates, the index's
///    capacity, and none comes near it: the class's task calls
///    [`check_class_headroom`] on the bound of its fullest cell, and the grid debug-asserts every
///    draw against [`CatalogueSystemId::INDEX_LIMIT`] and clamps it.
/// 8. **A placed class.** [`class`](Self::class) has a cell size. A process for
///    [`ClassId::TIDAL_DISRUPTION_VICTIM`], which is never placed, is refused: no
///    [`CatalogueCellKey`] exists for it, so it has no cell and resolves nothing.
///
/// # Examples
///
/// A toy class, not physics: four candidates expected in every 512 ly cell, half of them thinned
/// and half of the rest failing the test. Implementing the trait is all a class needs to be placed
/// on its own grid and resolved by ID.
///
/// ```
/// use hyperion_sim::Seed;
/// use hyperion_sim::galaxy::Galaxy;
/// use hyperion_sim::galaxy::catalogue_classes::{
///     CatalogueCellKey, CatalogueClassCell, ClassId, ClassProcess, resolve_entry,
/// };
/// use hyperion_sim::id::{CatalogueSystemId, SystemId};
/// use hyperion_sim::rng::{ObjectKey, Stream, Threshold, tags};
/// use hyperion_sim::units::PerCubicLightYear;
///
/// struct Toy;
///
/// impl ClassProcess for Toy {
///     type Candidate = u64;
///     type Entry = u64;
///
///     fn class(&self) -> ClassId {
///         ClassId::CORE_COLLAPSE
///     }
///
///     fn bound(&self, _: &Galaxy, cell: &CatalogueCellKey) -> PerCubicLightYear {
///         PerCubicLightYear::new(4.0 / cell.volume_ly3())
///     }
///
///     fn candidate(
///         &self,
///         galaxy: &Galaxy,
///         _: &CatalogueCellKey,
///         id: CatalogueSystemId,
///         bound: PerCubicLightYear,
///     ) -> Option<u64> {
///         let key = ObjectKey::from(SystemId::from(id));
///         let mut stream = Stream::open(galaxy.seed(), tags::SELFTEST_STREAM, key);
///         let density = 0.5 * bound.value();
///         let accepted = stream.decide(Threshold::from_ratio(density, bound.value()));
///         accepted.then(|| stream.next_u64())
///     }
///
///     fn test(&self, _: &Galaxy, mark: u64) -> Option<u64> {
///         (mark >> 63 == 0).then_some(mark)
///     }
///
///     fn members(&self, _: &u64) -> u8 {
///         1
///     }
/// }
///
/// let galaxy = Galaxy::new(Seed::new(9));
/// let key = CatalogueCellKey::new(ClassId::CORE_COLLAPSE, [0, 50, 0])?;
/// let cell = CatalogueClassCell::generate(&galaxy, &Toy, key);
/// assert!(cell.entries().len() <= usize::try_from(cell.candidates())?);
/// for entry in cell.entries() {
///     let member = resolve_entry(&galaxy, &Toy, entry.id())?;
///     assert_eq!(member.entry(), entry);
/// }
/// # Ok::<(), Box<dyn std::error::Error>>(())
/// ```
pub trait ClassProcess {
    /// A candidate the thinning accepted, with the marks the class's test reads.
    type Candidate;

    /// A kept candidate, what a cell holds and a resolve returns: for a supernova class, its
    /// record, its stars and its `SupernovaEntry`.
    type Entry;

    /// The class, which has a cell size ([`ClassId::cell_log2_ly`]): the grid takes the cell's
    /// size from the registry, never from a second copy.
    fn class(&self) -> ClassId;

    /// An upper bound on the density of the class's candidates over `cell`'s closed box, per cubic
    /// light-year: the cell's candidate count is a Poisson draw of mean the bound × the cell's
    /// volume, as plan 03's `layer_bound` × `volume_ly3`. For a supernova class it is P09.T33.a's
    /// envelope, the site density's bound × the thinning cap × the largest death rate.
    ///
    /// The grid evaluates it once per cell and hands the same value to every candidate's
    /// thinning. It must be finite and non-negative, and its mean, the bound × the cell's
    /// volume, at most 2³¹, the Poisson sampler's limit; the count panics otherwise.
    fn bound(&self, galaxy: &Galaxy, cell: &CatalogueCellKey) -> PerCubicLightYear;

    /// Candidate `id` (member 0) of `cell`, drawn on its own streams and accepted on its density
    /// ÷ `bound`, the cell's bound, or `None` if the thinning rejects it.
    fn candidate(
        &self,
        galaxy: &Galaxy,
        cell: &CatalogueCellKey,
        id: CatalogueSystemId,
        bound: PerCubicLightYear,
    ) -> Option<Self::Candidate>;

    /// The class's test on an accepted candidate: the entry it is kept as, or `None` if the test
    /// rejects it, which thins it like any other.
    fn test(&self, galaxy: &Galaxy, candidate: Self::Candidate) -> Option<Self::Entry>;

    /// How many members `entry` has, 1–16: member 0 is the entry itself, and members 1 to this
    /// − 1 its further members, numbered without gaps (P09.T34.a's surviving donor is member 1).
    fn members(&self, entry: &Self::Entry) -> u8;
}

/// One entry of a class cell: its candidate's ID, its number of members and what the class kept
/// (plan 09, P09.T32).
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct CatalogueEntry<E> {
    id: CatalogueSystemId,
    members: u8,
    value: E,
}

impl<E> CatalogueEntry<E> {
    /// The entry's ID: member 0 of its candidate, which keys its streams.
    #[must_use]
    pub const fn id(&self) -> CatalogueSystemId {
        self.id
    }

    /// How many members the entry has, 1–16.
    #[must_use]
    pub const fn members(&self) -> u8 {
        self.members
    }

    /// What the class kept.
    #[must_use]
    pub const fn value(&self) -> &E {
        &self.value
    }

    /// What the class kept, by value.
    #[must_use]
    pub fn into_value(self) -> E {
        self.value
    }

    /// The ID of member `member` of the entry, or `None` for a member it does not have.
    ///
    /// # Panics
    ///
    /// Never: a member below the entry's count is below 16, and the rest is the entry's own ID.
    #[must_use]
    pub fn member_id(&self, member: u8) -> Option<CatalogueSystemId> {
        (member < self.members).then(|| {
            let id = self.id;
            CatalogueSystemId::new(id.class(), id.cell(), id.index(), member)
                .expect("a member under 16 of a valid ID is a valid ID")
        })
    }
}

/// A resolved `111` ID: the entry it belongs to and which of its members it names (plan 09,
/// P09.T32).
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct CatalogueMember<E> {
    entry: CatalogueEntry<E>,
    member: u8,
}

impl<E> CatalogueMember<E> {
    /// The member's ID, the one resolved.
    ///
    /// # Panics
    ///
    /// Never: the member was checked against the entry's count when it was resolved.
    #[must_use]
    pub fn id(&self) -> CatalogueSystemId {
        self.entry
            .member_id(self.member)
            .expect("a resolved member is one of its entry's")
    }

    /// Which member of the entry: 0 is the entry itself.
    #[must_use]
    pub const fn member(&self) -> u8 {
        self.member
    }

    /// The entry the member belongs to.
    #[must_use]
    pub const fn entry(&self) -> &CatalogueEntry<E> {
        &self.entry
    }

    /// The entry the member belongs to, by value.
    #[must_use]
    pub fn into_entry(self) -> CatalogueEntry<E> {
        self.entry
    }
}

/// One class's catalogue cell, generated by thinning (plan 09, P09.T32): its candidate count and
/// its entries, in index order.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct CatalogueClassCell<E> {
    key: CatalogueCellKey,
    candidates: u32,
    entries: Vec<CatalogueEntry<E>>,
}

impl<E> CatalogueClassCell<E> {
    /// The cell `key` of `process`'s class: every candidate the thinning and the class's test
    /// keep, in index order.
    ///
    /// The bound is evaluated once and handed to the count and to every candidate's thinning, so
    /// [`resolve_entry`] reproduces each entry bit for bit without generating the cell. The count
    /// is one Poisson draw on `class.cell` keyed by the cell's [`word`](CatalogueCellKey::word),
    /// clamped to at most 2²⁴.
    ///
    /// # Panics
    ///
    /// - If `key` is not a cell of `process`'s class: a caller's broken invariant.
    /// - If the bound times the cell's volume is negative, not a number or above 2³¹, the Poisson
    ///   sampler's limit: a broken invariant in the class's bound.
    /// - In debug builds, if the count reaches past 2²⁴ candidates, which
    ///   [`check_class_headroom`] rules out and the clamp would otherwise hide; or if the class
    ///   gives an entry no members or more than 16.
    ///
    /// # Examples
    ///
    /// A chart that lists a class's entries near a point generates the cells about it; the cell
    /// is a pure function of the galaxy and the key, so a caller may cache it.
    ///
    /// ```
    /// use hyperion_sim::Seed;
    /// use hyperion_sim::coords::GalacticPosition;
    /// use hyperion_sim::galaxy::Galaxy;
    /// use hyperion_sim::galaxy::catalogue_classes::{
    ///     CatalogueCellKey, CatalogueClassCell, ClassId, ClassProcess,
    /// };
    /// use hyperion_sim::id::{CatalogueSystemId, SystemId};
    /// use hyperion_sim::rng::{ObjectKey, Stream, tags};
    /// use hyperion_sim::units::PerCubicLightYear;
    ///
    /// # struct Toy;
    /// # impl ClassProcess for Toy {
    /// #     type Candidate = u64;
    /// #     type Entry = u64;
    /// #     fn class(&self) -> ClassId { ClassId::STELLAR_MERGER }
    /// #     fn bound(&self, _: &Galaxy, cell: &CatalogueCellKey) -> PerCubicLightYear {
    /// #         PerCubicLightYear::new(6.0 / cell.volume_ly3())
    /// #     }
    /// #     fn candidate(
    /// #         &self,
    /// #         galaxy: &Galaxy,
    /// #         _: &CatalogueCellKey,
    /// #         id: CatalogueSystemId,
    /// #         _: PerCubicLightYear,
    /// #     ) -> Option<u64> {
    /// #         let key = ObjectKey::from(SystemId::from(id));
    /// #         Some(Stream::open(galaxy.seed(), tags::SELFTEST_STREAM, key).next_u64())
    /// #     }
    /// #     fn test(&self, _: &Galaxy, mark: u64) -> Option<u64> { Some(mark) }
    /// #     fn members(&self, _: &u64) -> u8 { 1 }
    /// # }
    /// let galaxy = Galaxy::new(Seed::new(9));
    /// // The 4,096 ly cell of a toy class (not physics, six candidates expected per cell) that
    /// // holds a point in the disc.
    /// let point = GalacticPosition::from_light_years([0.0, 26_000.0, 20.0]).ok_or("in range")?;
    /// let key = CatalogueCellKey::containing(ClassId::STELLAR_MERGER, &point).ok_or("placed")?;
    /// let cell = CatalogueClassCell::generate(&galaxy, &Toy, key);
    /// assert_eq!(cell, CatalogueClassCell::generate(&galaxy, &Toy, key));
    /// for (entry, index) in cell.entries().iter().zip(0..) {
    ///     // The toy keeps every candidate, so the entries are candidates 0, 1, 2, …
    ///     assert_eq!(entry.id(), key.candidate_id(index, 0)?);
    ///     assert!(entry.id().is_aligned_to(12));
    /// }
    /// # Ok::<(), Box<dyn std::error::Error>>(())
    /// ```
    #[must_use]
    pub fn generate<P: ClassProcess<Entry = E>>(
        galaxy: &Galaxy,
        process: &P,
        key: CatalogueCellKey,
    ) -> Self {
        assert_eq!(
            key.class(),
            process.class(),
            "a class cell is generated by its own class's process"
        );
        let bound = process.bound(galaxy, &key);
        let candidates = candidate_count(galaxy.seed(), &key, bound);
        let entries = (0..candidates)
            .filter_map(|index| {
                let id = key
                    .candidate_id(index, 0)
                    .expect("a count held under 2^24 numbers every candidate");
                keep(galaxy, process, &key, id, bound)
            })
            .collect();
        Self {
            key,
            candidates,
            entries,
        }
    }

    /// The cell's key.
    #[must_use]
    pub const fn key(&self) -> CatalogueCellKey {
        self.key
    }

    /// The cell's candidate count: the IDs with index below it are its candidates, kept or not.
    #[must_use]
    pub const fn candidates(&self) -> u32 {
        self.candidates
    }

    /// The cell's entries, in index order.
    #[must_use]
    pub fn entries(&self) -> &[CatalogueEntry<E>] {
        &self.entries
    }

    /// The cell's entries, in index order, by value.
    #[must_use]
    pub fn into_entries(self) -> Vec<CatalogueEntry<E>> {
        self.entries
    }
}

/// The entry and member a `111` ID names in `process`'s class: one bound, one count and one
/// candidate, never the cell (plan 09, P09.T32).
///
/// It answers exactly as [`CatalogueClassCell::generate`] would: the same bound is evaluated for
/// the ID's cell and handed to the count and to the candidate's thinning.
///
/// # Errors
///
/// [`ResolveSystemError::NoSuchSystem`] for:
///
/// - an ID of another class than `process`'s;
/// - an ID that names no class cell ([`CatalogueCellKey::of`]): a free class value, a class that
///   is never placed, or a cell not aligned to the class's size, so that a misaligned ID never
///   aliases an aligned one;
/// - an index at or beyond the cell's candidate count;
/// - a candidate the thinning or the class's test rejects;
/// - a member the entry does not have.
///
/// # Panics
///
/// As [`CatalogueClassCell::generate`], on a bound that is not finite and non-negative or whose
/// mean, the bound × the cell's volume, is above 2³¹, and in
/// debug builds on a count past 2²⁴ or an entry with no members or more than 16.
///
/// # Examples
///
/// A sensor's log names a host by its ID alone; resolving it reruns its one candidate, with no
/// cell generated:
///
/// ```
/// use hyperion_sim::Seed;
/// use hyperion_sim::galaxy::Galaxy;
/// use hyperion_sim::galaxy::catalogue_classes::{
///     CatalogueCellKey, CatalogueClassCell, ClassId, ClassProcess, resolve_entry,
/// };
/// use hyperion_sim::galaxy::placement::ResolveSystemError;
/// use hyperion_sim::id::{CatalogueSystemId, SystemId};
/// use hyperion_sim::rng::{ObjectKey, Stream, tags};
/// use hyperion_sim::units::PerCubicLightYear;
///
/// # struct Toy;
/// # impl ClassProcess for Toy {
/// #     type Candidate = u64;
/// #     type Entry = u64;
/// #     fn class(&self) -> ClassId { ClassId::TYPE_IA }
/// #     fn bound(&self, _: &Galaxy, cell: &CatalogueCellKey) -> PerCubicLightYear {
/// #         PerCubicLightYear::new(8.0 / cell.volume_ly3())
/// #     }
/// #     fn candidate(
/// #         &self,
/// #         galaxy: &Galaxy,
/// #         _: &CatalogueCellKey,
/// #         id: CatalogueSystemId,
/// #         _: PerCubicLightYear,
/// #     ) -> Option<u64> {
/// #         let key = ObjectKey::from(SystemId::from(id));
/// #         Some(Stream::open(galaxy.seed(), tags::SELFTEST_STREAM, key).next_u64())
/// #     }
/// #     fn test(&self, _: &Galaxy, mark: u64) -> Option<u64> { (mark >> 63 == 0).then_some(mark) }
/// #     fn members(&self, _: &u64) -> u8 { 2 }
/// # }
/// let galaxy = Galaxy::new(Seed::new(9));
/// let key = CatalogueCellKey::new(ClassId::TYPE_IA, [0, 50, 0])?;
/// let cell = CatalogueClassCell::generate(&galaxy, &Toy, key);
/// let entry = cell.entries().first().ok_or("the toy keeps about four of eight")?;
///
/// // The toy's entries have two members; the second is a system with an ID of its own.
/// let saved = entry.member_id(1).ok_or("two members")?;
/// let survivor = resolve_entry(&galaxy, &Toy, saved)?;
/// assert_eq!((survivor.id(), survivor.member()), (saved, 1));
/// assert_eq!(survivor.entry(), entry);
/// // A third member, or an index past the cell's candidates, names nothing.
/// let third = CatalogueSystemId::new(1, saved.cell(), saved.index(), 2)?;
/// assert_eq!(resolve_entry(&galaxy, &Toy, third), Err(ResolveSystemError::NoSuchSystem));
/// let past = key.candidate_id(cell.candidates(), 0)?;
/// assert_eq!(resolve_entry(&galaxy, &Toy, past), Err(ResolveSystemError::NoSuchSystem));
/// # Ok::<(), Box<dyn std::error::Error>>(())
/// ```
pub fn resolve_entry<P: ClassProcess>(
    galaxy: &Galaxy,
    process: &P,
    id: CatalogueSystemId,
) -> Result<CatalogueMember<P::Entry>, ResolveSystemError> {
    if id.class() != process.class().value() {
        return Err(ResolveSystemError::NoSuchSystem);
    }
    // Every way an ID can fail to name a class cell is "no such system" to a resolver; the
    // reason is `CatalogueCellKey::of`'s to report to a caller who asks it.
    let key = CatalogueCellKey::of(id).map_err(|_| ResolveSystemError::NoSuchSystem)?;
    let bound = process.bound(galaxy, &key);
    if id.index() >= candidate_count(galaxy.seed(), &key, bound) {
        return Err(ResolveSystemError::NoSuchSystem);
    }
    let entry =
        keep(galaxy, process, &key, entry_of(id), bound).ok_or(ResolveSystemError::NoSuchSystem)?;
    if id.member() >= entry.members() {
        return Err(ResolveSystemError::NoSuchSystem);
    }
    Ok(CatalogueMember {
        entry,
        member: id.member(),
    })
}

/// What a caller does with a class's process, whatever the process's entry type: the generic half
/// of a dispatch on [`ClassId`] through a [`ClassLookup`] (plan 09, P09.T32).
///
/// [`ClassLookup`]'s example implements one, counting a class's entries about a point.
pub trait ClassVisitor {
    /// What the visit returns, the same for every class.
    type Output;

    /// Visits `process`.
    fn visit<P: ClassProcess>(self, process: &P) -> Self::Output;
}

/// What a caller does with a member [`resolve`] found, whatever its class's entry type (plan 09,
/// P09.T32).
pub trait MemberVisitor {
    /// What the visit returns, the same for every class.
    type Output;

    /// Visits `member`, resolved in `process`'s class.
    fn visit<P: ClassProcess>(self, process: &P, member: CatalogueMember<P::Entry>)
    -> Self::Output;
}

/// A lookup of class processes by [`ClassId`]: [`ProductionClasses`], or a test's (plan 09,
/// P09.T32).
///
/// An implementation is one `match` on the class that builds the class's process and hands it to
/// the visitor, so that every class keeps its own entry type and the code that visits it is
/// generic.
///
/// # Examples
///
/// A merge of the catalogue into a range query (P09.T37) asks each class for its entries about a
/// point, whatever the class's entry type: a [`ClassVisitor`] that walks the class's cells, and a
/// lookup with one arm per class whose process is built.
///
/// ```
/// use hyperion_sim::Seed;
/// use hyperion_sim::coords::GalacticPosition;
/// use hyperion_sim::galaxy::Galaxy;
/// use hyperion_sim::galaxy::catalogue_classes::{
///     ALL_CLASSES, CatalogueCellKey, CatalogueClassCell, ClassId, ClassLookup, ClassProcess,
///     ClassVisitor, cells_in_sphere,
/// };
/// use hyperion_sim::galaxy::query::QuerySphere;
/// use hyperion_sim::id::{CatalogueSystemId, SystemId};
/// use hyperion_sim::rng::{ObjectKey, Stream, tags};
/// use hyperion_sim::time::UniverseTime;
/// use hyperion_sim::units::{LightYears, PerCubicLightYear};
///
/// # struct Toy;
/// # impl ClassProcess for Toy {
/// #     type Candidate = u64;
/// #     type Entry = u64;
/// #     fn class(&self) -> ClassId { ClassId::STELLAR_MERGER }
/// #     fn bound(&self, _: &Galaxy, cell: &CatalogueCellKey) -> PerCubicLightYear {
/// #         PerCubicLightYear::new(2.0 / cell.volume_ly3())
/// #     }
/// #     fn candidate(
/// #         &self,
/// #         galaxy: &Galaxy,
/// #         _: &CatalogueCellKey,
/// #         id: CatalogueSystemId,
/// #         _: PerCubicLightYear,
/// #     ) -> Option<u64> {
/// #         let key = ObjectKey::from(SystemId::from(id));
/// #         Some(Stream::open(galaxy.seed(), tags::SELFTEST_STREAM, key).next_u64())
/// #     }
/// #     fn test(&self, _: &Galaxy, mark: u64) -> Option<u64> { Some(mark) }
/// #     fn members(&self, _: &u64) -> u8 { 1 }
/// # }
/// /// A lookup with one class's process, a toy (not physics) on the merger class.
/// struct OneToy;
///
/// impl ClassLookup for OneToy {
///     fn visit_class<V: ClassVisitor>(
///         &self,
///         _: &Galaxy,
///         class: ClassId,
///         visitor: V,
///     ) -> Option<V::Output> {
///         match class {
///             ClassId::STELLAR_MERGER => Some(visitor.visit(&Toy)),
///             _ => None,
///         }
///     }
/// }
///
/// /// How many entries a class has in the cells about a sphere.
/// struct EntriesNear<'a> {
///     galaxy: &'a Galaxy,
///     sphere: &'a QuerySphere,
/// }
///
/// impl ClassVisitor for EntriesNear<'_> {
///     type Output = usize;
///
///     fn visit<P: ClassProcess>(self, process: &P) -> usize {
///         cells_in_sphere(process.class(), self.sphere)
///             .map(|key| CatalogueClassCell::generate(self.galaxy, process, key).entries().len())
///             .sum()
///     }
/// }
///
/// let galaxy = Galaxy::new(Seed::new(9));
/// let sun = GalacticPosition::from_light_years([0.0, 26_000.0, 20.0]).ok_or("in range")?;
/// let sphere =
///     QuerySphere::new(sun, LightYears::new(50.0), UniverseTime::EPOCH, LightYears::ZERO)?;
/// let counts: Vec<Option<usize>> = ALL_CLASSES
///     .into_iter()
///     .map(|class| {
///         let near = EntriesNear { galaxy: &galaxy, sphere: &sphere };
///         OneToy.visit_class(&galaxy, class, near)
///     })
///     .collect();
/// // Only the merger class has a process; its 20 cells about the point expect two entries each.
/// assert!(counts[2].is_some_and(|n| n > 10));
/// assert_eq!(counts.iter().filter(|n| n.is_some()).count(), 1);
/// # Ok::<(), Box<dyn std::error::Error>>(())
/// ```
pub trait ClassLookup {
    /// Hands the process of `class` in `galaxy` to `visitor`, or returns `None` for a class this
    /// lookup has no process for.
    fn visit_class<V: ClassVisitor>(
        &self,
        galaxy: &Galaxy,
        class: ClassId,
        visitor: V,
    ) -> Option<V::Output>;
}

/// The production lookup of class processes (plan 09, P09.T32): at P09.T32 it has none.
///
/// Each class's process is registered here by the task that builds it, as one arm,
/// `ClassId::CORE_COLLAPSE => Some(visitor.visit(&CoreCollapseProcess::new(galaxy)))`:
/// [`CORE_COLLAPSE`](ClassId::CORE_COLLAPSE) by P09.T33.a, [`TYPE_IA`](ClassId::TYPE_IA) by
/// P09.T34.a, [`LUMINOUS_BLUE_VARIABLE`](ClassId::LUMINOUS_BLUE_VARIABLE) by P09.T43, and plan
/// 11's five by P11.T8. [`TIDAL_DISRUPTION_VICTIM`](ClassId::TIDAL_DISRUPTION_VICTIM) is never
/// placed and gets none. Until then every `111` ID that reaches the grid answers
/// [`NoSuchSystem`](ResolveSystemError::NoSuchSystem).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct ProductionClasses;

impl ClassLookup for ProductionClasses {
    fn visit_class<V: ClassVisitor>(
        &self,
        _galaxy: &Galaxy,
        _class: ClassId,
        _visitor: V,
    ) -> Option<V::Output> {
        None
    }
}

/// The member a `111` ID names, handed to `visitor`, if `lookup` has its class's process and that
/// process keeps it (plan 09, P09.T32): the resolve of the `111` prefix.
///
/// The ID must first name a class cell ([`CatalogueCellKey::of`]); then the lookup's process for
/// the class answers as [`resolve_entry`] does.
///
/// # Errors
///
/// [`ResolveSystemError::NoSuchSystem`] for a class with no process in `lookup`, which takes in a
/// free class value (9–63), [`TIDAL_DISRUPTION_VICTIM`](ClassId::TIDAL_DISRUPTION_VICTIM) and a
/// registered class whose process is not built yet; for a cell that fails
/// [`is_aligned_to`](CatalogueSystemId::is_aligned_to) at the class's cell size; and for each of
/// [`resolve_entry`]'s cases.
///
/// # Panics
///
/// As [`resolve_entry`].
///
/// # Examples
///
/// Every catalogue ID that arrives from a save or the protocol will go through the production
/// lookup once P09.T33.a points plan 03's resolve at it. No class's process is built yet, so each
/// one names nothing:
///
/// ```
/// use hyperion_sim::Seed;
/// use hyperion_sim::galaxy::Galaxy;
/// use hyperion_sim::galaxy::catalogue_classes::{
///     CatalogueMember, ClassId, ClassProcess, MemberVisitor, ProductionClasses, resolve,
/// };
/// use hyperion_sim::galaxy::placement::ResolveSystemError;
/// use hyperion_sim::id::{CatalogueSystemId, SystemId, SystemIdKind};
///
/// /// What a caller keeps of a resolved member: here, its ID.
/// struct MemberId;
///
/// impl MemberVisitor for MemberId {
///     type Output = CatalogueSystemId;
///
///     fn visit<P: ClassProcess>(
///         self,
///         _: &P,
///         member: CatalogueMember<P::Entry>,
///     ) -> CatalogueSystemId {
///         member.id()
///     }
/// }
///
/// let galaxy = Galaxy::new(Seed::new(9));
/// let saved = SystemId::from_raw(0xFC38_8409_A000_0761)?;
/// let SystemIdKind::Catalogue(id) = saved.kind() else {
///     return Err("a catalogue system".into());
/// };
/// assert_eq!(ClassId::from_value(id.class()), Some(ClassId::NEUTRON_STAR_MERGER));
/// assert_eq!(
///     resolve(&galaxy, &ProductionClasses, id, MemberId),
///     Err(ResolveSystemError::NoSuchSystem)
/// );
/// # Ok::<(), Box<dyn std::error::Error>>(())
/// ```
pub fn resolve<L: ClassLookup, V: MemberVisitor>(
    galaxy: &Galaxy,
    lookup: &L,
    id: CatalogueSystemId,
    visitor: V,
) -> Result<V::Output, ResolveSystemError> {
    // As in `resolve_entry`: an ID that names no class cell names no system.
    let key = CatalogueCellKey::of(id).map_err(|_| ResolveSystemError::NoSuchSystem)?;
    lookup
        .visit_class(
            galaxy,
            key.class(),
            Resolve {
                galaxy,
                id,
                visitor,
            },
        )
        .ok_or(ResolveSystemError::NoSuchSystem)?
}

/// [`resolve`]'s visit of the lookup's process.
struct Resolve<'g, V> {
    galaxy: &'g Galaxy,
    id: CatalogueSystemId,
    visitor: V,
}

impl<V: MemberVisitor> ClassVisitor for Resolve<'_, V> {
    type Output = Result<V::Output, ResolveSystemError>;

    fn visit<P: ClassProcess>(self, process: &P) -> Self::Output {
        let member = resolve_entry(self.galaxy, process, self.id)?;
        Ok(self.visitor.visit(process, member))
    }
}

/// The entry candidate `id` of `key` is kept as, under the cell's `bound`, if the thinning and the
/// class's test both keep it.
#[must_use]
fn keep<P: ClassProcess>(
    galaxy: &Galaxy,
    process: &P,
    key: &CatalogueCellKey,
    id: CatalogueSystemId,
    bound: PerCubicLightYear,
) -> Option<CatalogueEntry<P::Entry>> {
    let candidate = process.candidate(galaxy, key, id, bound)?;
    let value = process.test(galaxy, candidate)?;
    let members = process.members(&value);
    debug_assert!(
        (1..=CatalogueSystemId::MEMBER_LIMIT).contains(&members),
        "the {} entry {id:?} has {members} members, not 1–16",
        process.class()
    );
    Some(CatalogueEntry {
        id,
        members: members.clamp(1, CatalogueSystemId::MEMBER_LIMIT),
        value,
    })
}

/// The expected number of candidates in `key` under `bound`: the bound × the cell's volume, the
/// count's Poisson mean.
#[must_use]
fn expected_candidates(key: &CatalogueCellKey, bound: PerCubicLightYear) -> f64 {
    bound.value() * key.volume_ly3()
}

/// How many candidates the cell draws: one Poisson draw of mean `bound` × the cell's volume, on
/// `class.cell` keyed by the cell's word, clamped to at most 2²⁴ (the brainstorm's thinning, step
/// 2).
///
/// # Panics
///
/// On a mean that is negative, not a number or above 2³¹ ([`Stream::poisson`]), and in debug
/// builds on a draw past 2²⁴, which [`check_class_headroom`] rules out.
#[must_use]
fn candidate_count(seed: Seed, key: &CatalogueCellKey, bound: PerCubicLightYear) -> u32 {
    let mean = expected_candidates(key, bound);
    let mut stream = Stream::open(seed, tags::CLASS_CELL, ObjectKey::cell(key.word()));
    let drawn = stream.poisson(mean);
    debug_assert!(
        drawn <= u64::from(CatalogueSystemId::INDEX_LIMIT),
        "the {} cell {:?} drew {drawn} candidates, past the 2^24 index: check_class_headroom \
         should have refused its bound",
        key.class(),
        key.cell(),
    );
    clamp_to_index(drawn)
}

/// A Poisson draw cut down to the 24-bit index, so that every candidate has an ID: a pure function
/// of the cell's own draw, so the same when one ID is resolved as when the cell is generated, and
/// never reached by a class that passes [`check_class_headroom`].
#[must_use]
fn clamp_to_index(drawn: u64) -> u32 {
    let capped = drawn.min(u64::from(CatalogueSystemId::INDEX_LIMIT));
    u32::try_from(capped).expect("a count capped at 2^24 fits in a u32")
}

/// How many standard deviations of a cell's Poisson draw must fit between a class's largest mean
/// and the 2²⁴ index: eight, about one chance in 10¹⁵ per cell of a draw past it, as plan 03 keeps
/// for the grid's layers (its Design note 6, `placement::check_index_headroom`).
const HEADROOM_SIGMAS: f64 = 8.0;

/// A class's fullest cell could draw more candidates than the 24-bit index numbers, or the class
/// has no cells (plan 09, P09.T32).
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum CheckClassHeadroomError {
    /// The class is never placed, so it has no cells to check
    /// ([`ClassId::TIDAL_DISRUPTION_VICTIM`]).
    NotPlaced(ClassId),
    /// The class's fullest cell expects `largest_mean` candidates, and that plus eight standard
    /// deviations exceeds `capacity`; a bound that is not finite and non-negative fails the same
    /// way.
    ClassTooDense {
        /// The class.
        class: ClassId,
        /// The largest bound × the class's cell volume.
        largest_mean: f64,
        /// The index's capacity, 2²⁴.
        capacity: u32,
    },
}

impl fmt::Display for CheckClassHeadroomError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::NotPlaced(class) => {
                write!(f, "the class {class} is never placed, so it has no cells")
            }
            Self::ClassTooDense {
                class,
                largest_mean,
                capacity,
            } => write!(
                f,
                "the class {class}'s fullest cell expects {largest_mean:.0} candidates, within \
                 eight standard deviations of its index capacity of {capacity}"
            ),
        }
    }
}

impl Error for CheckClassHeadroomError {}

/// Checks that no cell of `class` can draw more candidates than the 24-bit index numbers, given
/// `largest_bound`, the class's bound over its fullest cell (plan 09, P09.T32).
///
/// The fullest cell's mean, `largest_bound` × the class's cell volume, plus eight standard
/// deviations of its Poisson draw must stay within [`CatalogueSystemId::INDEX_LIMIT`], as plan
/// 03's `check_index_headroom` asks of the grid's layers. Each class's task finds its largest
/// bound (over every cell, or a partition of the root cube that its bound is monotone on) and
/// calls this in its tests; the Poisson sampler's own limit, 2³¹, is far above. Nothing on the
/// hot path calls it: the count clamps instead.
///
/// # Errors
///
/// - [`CheckClassHeadroomError::NotPlaced`] for a class with no cell size.
/// - [`CheckClassHeadroomError::ClassTooDense`] when the mean plus eight standard deviations
///   exceeds 2²⁴, or the bound is not finite and non-negative.
///
/// # Examples
///
/// A class whose fullest 512 ly cell expects ten thousand candidates has room to spare; one whose
/// cell would expect 16.75 million has not, since eight standard deviations above that pass 2²⁴,
/// 16,777,216:
///
/// ```
/// use hyperion_sim::galaxy::catalogue_classes::{
///     CheckClassHeadroomError, ClassId, check_class_headroom,
/// };
/// use hyperion_sim::units::PerCubicLightYear;
///
/// let volume = 512.0 * 512.0 * 512.0;
/// let sparse = PerCubicLightYear::new(1e4 / volume);
/// assert_eq!(check_class_headroom(ClassId::CORE_COLLAPSE, sparse), Ok(()));
/// let full = PerCubicLightYear::new(16.75e6 / volume);
/// assert!(matches!(
///     check_class_headroom(ClassId::CORE_COLLAPSE, full),
///     Err(CheckClassHeadroomError::ClassTooDense { .. })
/// ));
/// ```
pub fn check_class_headroom(
    class: ClassId,
    largest_bound: PerCubicLightYear,
) -> Result<(), CheckClassHeadroomError> {
    // Any cell of the class has the class's volume; an unplaced class has none.
    let key = CatalogueCellKey::new(class, [0, 0, 0])
        .map_err(|_| CheckClassHeadroomError::NotPlaced(class))?;
    let largest_mean = expected_candidates(&key, largest_bound);
    let capacity = CatalogueSystemId::INDEX_LIMIT;
    // A NaN or negative mean fails the comparison, through its square root.
    if largest_mean + HEADROOM_SIGMAS * largest_mean.sqrt() <= f64::from(capacity) {
        Ok(())
    } else {
        Err(CheckClassHeadroomError::ClassTooDense {
            class,
            largest_mean,
            capacity,
        })
    }
}

/// The largest whole reach of a walk from its centre, light-years: 2³⁴, beyond the far corner of
/// the root cube from any centre whose light-year cell is an `i32`. A larger radius changes
/// nothing.
const MAX_REACH_LY: f64 = 17_179_869_184.0;

/// Every cell of `class` whose entries can lie in `sphere`: the cells whose closed box meets the
/// sphere of `sphere.radius()` + [`LIFETIME_REACH`] about its centre, clipped to the root cube, in
/// ascending x, then y, then z (plan 09, P09.T32).
///
/// An entry stays within [`LIFETIME_REACH`], 4,096 ly, of its cell at every time it serves (the
/// [`ClassProcess`] contract), so an entry inside the sphere at any time lies in one of these
/// cells. That is the brainstorm's "the entry's lifetime is held to 4,096 ly ÷ its fastest
/// member's speed, so that lookups stay within a known number of rings of cells": 4,096 ly ÷ 512
/// ly is eight rings of a 512 ly class's cells about the sphere, and one ring of a 4,096 ly
/// class's. The sphere's own [`padded_radius`](QuerySphere::padded_radius), the grid layers' pad
/// for drift, is not read: the reach is the class's pad.
///
/// A cell is kept when the squared distance from the centre to its closed box is at most the
/// padded radius squared, each axis's gap taken from the whole light-years between the centre's
/// cell and the box's face, an exact integer, and the centre's fraction of a light-year, as plan
/// 03's walk of the grid's layers (`query::cells_in_sphere`) takes it. A class that is never
/// placed has no cells. P09.T37's `CatalogueClassSource::cells_in_sphere(class, sphere)` wraps
/// this.
///
/// # Examples
///
/// Plan 12's alerts and a chart's catalogue walk the cells about a point, here a 50 ly sphere at
/// the Sun-like point: a few thousand 512 ly cells, and about twenty 4,096 ly ones.
///
/// ```
/// use hyperion_sim::coords::GalacticPosition;
/// use hyperion_sim::galaxy::catalogue_classes::{ClassId, cells_in_sphere};
/// use hyperion_sim::galaxy::query::QuerySphere;
/// use hyperion_sim::time::UniverseTime;
/// use hyperion_sim::units::LightYears;
///
/// let sun = GalacticPosition::from_light_years([0.0, 26_000.0, 20.0]).ok_or("in range")?;
/// let sphere =
///     QuerySphere::new(sun, LightYears::new(50.0), UniverseTime::EPOCH, LightYears::ZERO)?;
/// let fine: Vec<_> = cells_in_sphere(ClassId::CORE_COLLAPSE, &sphere).collect();
/// let coarse = cells_in_sphere(ClassId::STELLAR_MERGER, &sphere).count();
/// assert!((2_500..3_200).contains(&fine.len()));
/// assert!((15..=32).contains(&coarse));
/// // In ascending order, the key's own.
/// assert!(fine.windows(2).all(|pair| pair[0] < pair[1]));
/// assert_eq!(cells_in_sphere(ClassId::TIDAL_DISRUPTION_VICTIM, &sphere).count(), 0);
/// # Ok::<(), Box<dyn std::error::Error>>(())
/// ```
pub fn cells_in_sphere(
    class: ClassId,
    sphere: &QuerySphere,
) -> impl Iterator<Item = CatalogueCellKey> + use<> {
    ClassWalk::new(class, sphere).into_iter().flat_map(|walk| {
        walk.cells(0).flat_map(move |x| {
            let gx2_ly2 = walk.gap_squared_ly2(0, x);
            walk.cells(1)
                .filter_map(move |y| {
                    walk.column(gx2_ly2 + walk.gap_squared_ly2(1, y))
                        .map(|z| (y, z))
                })
                .flat_map(move |(y, (z_first, z_last))| {
                    (z_first..=z_last).map(move |z| walk.key([x, y, z]))
                })
        })
    })
}

/// One axis of a class walk: where the centre is, and the range of cells to look at.
#[derive(Debug, Clone, Copy)]
struct Axis {
    /// The centre's whole light-year on this axis.
    centre_ly: i64,
    /// The centre's distance above that light-year, light-years, in `[0, 1)`.
    fraction_ly: f64,
    /// The cell holding the centre, on the class's grid.
    centre_cell: i64,
    /// The first and last cells of the padded sphere's bounding box, clipped to the root cube.
    first: i64,
    last: i64,
}

/// A walk of one class's cells over one sphere padded by the reach.
#[derive(Debug, Clone, Copy)]
struct ClassWalk {
    class: ClassId,
    /// The cell edge, light-years.
    edge_ly: i64,
    axes: [Axis; 3],
    /// The padded radius squared, ly².
    radius_squared_ly2: f64,
}

impl ClassWalk {
    /// The walk of `class` over `sphere`, or `None` for a class that is never placed or a sphere
    /// that misses the root cube's cells altogether.
    #[must_use]
    fn new(class: ClassId, sphere: &QuerySphere) -> Option<Self> {
        let log2 = class.cell_log2_ly()?;
        let edge_ly = 1_i64 << log2;
        let padded = (sphere.radius() + LIFETIME_REACH).value();
        // Whole light-years that cover the padded radius; the clamp keeps any finite radius in
        // range and changes no cell, since 2³⁴ ly reaches past the cube from any centre.
        #[expect(
            clippy::cast_possible_truncation,
            reason = "a whole number of light-years in [1, 2^34], exact in i64"
        )]
        let reach = padded.ceil().clamp(1.0, MAX_REACH_LY) as i64;
        // The cube's cells on this grid run from −h to h − 1.
        let half = i64::from(ROOT_HALF_WIDTH_LY) >> log2;
        let cell = sphere.centre().cell().to_array();
        let offset = sphere.centre().offset_metres();
        let axes = [0, 1, 2].map(|axis| {
            let centre_ly = i64::from(cell[axis]);
            Axis {
                centre_ly,
                fraction_ly: offset[axis] / METRES_PER_LIGHT_YEAR,
                centre_cell: centre_ly.div_euclid(edge_ly),
                // [c − R, c + R] lies inside [c_ly − reach, c_ly + 1 + reach]; a cell that only
                // touches it has a face at an end, so the range reaches one light-year beyond on
                // both sides, as plan 03's walk does.
                first: (centre_ly - reach - 1).div_euclid(edge_ly).max(-half),
                last: (centre_ly + 1 + reach).div_euclid(edge_ly).min(half - 1),
            }
        });
        if axes.iter().any(|axis| axis.first > axis.last) {
            return None;
        }
        Some(Self {
            class,
            edge_ly,
            axes,
            radius_squared_ly2: padded * padded,
        })
    }

    /// The cells of the bounding box on one axis.
    #[must_use]
    fn cells(self, axis: usize) -> std::ops::RangeInclusive<i64> {
        self.axes[axis].first..=self.axes[axis].last
    }

    /// The squared distance, ly², from the centre to the slab of `cell` on one axis: zero inside
    /// it, otherwise the gap to the nearer face.
    #[must_use]
    fn gap_squared_ly2(self, axis: usize, cell: i64) -> f64 {
        let axis = &self.axes[axis];
        let low = cell * self.edge_ly;
        let high = low + self.edge_ly;
        let gap_ly = if axis.centre_ly >= high {
            // At or beyond the high face: c − high = (c_ly − high) + fraction.
            exact(axis.centre_ly - high) + axis.fraction_ly
        } else if low > axis.centre_ly {
            // Below the low face: low − c = (low − c_ly) − fraction, with low ≥ c_ly + 1.
            exact(low - axis.centre_ly) - axis.fraction_ly
        } else {
            0.0
        };
        gap_ly * gap_ly
    }

    /// The first and last cells in z of the column whose squared distance in x and y is
    /// `gxy2_ly2`, or `None` if no cell of it meets the padded sphere.
    ///
    /// The kept cells of a column are contiguous about its nearest cell, since the gap falls
    /// towards the centre's cell and rises beyond it and float addition is monotone, so the run is
    /// grown outwards from the nearest cell one cell at a time: at most 2 × 9 + 2 tests per column
    /// at 512 ly for a sphere of 50 ly.
    #[must_use]
    fn column(self, gxy2_ly2: f64) -> Option<(i64, i64)> {
        let z = self.axes[2];
        let inside =
            |cell: i64| gxy2_ly2 + self.gap_squared_ly2(2, cell) <= self.radius_squared_ly2;
        let nearest = z.centre_cell.clamp(z.first, z.last);
        if !inside(nearest) {
            return None;
        }
        let mut first = nearest;
        while first > z.first && inside(first - 1) {
            first -= 1;
        }
        let mut last = nearest;
        while last < z.last && inside(last + 1) {
            last += 1;
        }
        Some((first, last))
    }

    /// The key of a cell of the walk.
    ///
    /// # Panics
    ///
    /// Never: the walk's cells lie in the root cube, whose class cells' coordinates fit in `i32`.
    #[must_use]
    fn key(self, cell: [i64; 3]) -> CatalogueCellKey {
        let cell = cell.map(|c| i32::try_from(c).expect("a cell of the root cube fits in i32"));
        CatalogueCellKey::new(self.class, cell).expect("a walk's cells are in the cube")
    }
}

/// A whole number of light-years as a float, exactly: every gap a walk takes is under 2⁵³.
#[must_use]
fn exact(ly: i64) -> f64 {
    #[expect(
        clippy::cast_precision_loss,
        reason = "a gap between i32 light-year cells and the root cube's faces is under 2^33, \
                  exact in f64"
    )]
    let value = ly as f64;
    value
}
