//! Test parameter sets for plan 09's clusters (P09.T7–T14): the Milky Way's globular clusters
//! and named ones.
//!
//! **Provenance.** [`milky_way_globulars`] is a reduced copy of Baumgardt and Hilker's catalogue of
//! Galactic globular clusters, version 4 (Baumgardt and Hilker 2018, MNRAS 478, 1520; Baumgardt et
//! al. 2019, MNRAS 482, 5138; Vasiliev and Baumgardt 2021, MNRAS 505, 5978), fetched on 2026-09-27
//! from `people.smp.uq.edu.au/HolgerBaumgardt/globular/`: its `combined_table.txt` (mass, core,
//! half-mass and tidal radii, central density, relaxation time, initial mass, mass-function slope,
//! central escape speed) and `orbits_table.txt` (galactocentric position, peri- and apocentre), for
//! the 165 clusters in both. The sim may not depend on `hyperion-fit`, which holds plan 15's copy,
//! so the numbers are committed here as the catalogue prints them (plan 09, "Test helpers").
//!
//! The catalogue's frame has the Sun on the −x axis; positions are given as it prints them and the
//! tests read only their radii.

/// One globular cluster of the Baumgardt–Hilker catalogue, as it prints it.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct CatalogueGlobular {
    /// The catalogue's name, such as `NGC_104`.
    pub name: &'static str,
    /// Present mass, M☉.
    pub mass: f64,
    /// Core radius, pc.
    pub core_radius_pc: f64,
    /// Three-dimensional half-mass radius, pc.
    pub half_mass_radius_pc: f64,
    /// Tidal radius, pc.
    pub tidal_radius_pc: f64,
    /// log₁₀ of the central density, M☉ pc⁻³.
    pub log_central_density: f64,
    /// Galactocentric position, kpc.
    pub position_kpc: [f64; 3],
    /// Pericentre, kpc.
    pub pericentre_kpc: f64,
    /// Apocentre, kpc.
    pub apocentre_kpc: f64,
    /// log₁₀ of the half-mass relaxation time, yr.
    pub log_relaxation_time: f64,
    /// log₁₀ of the initial mass, M☉.
    pub log_initial_mass: f64,
    /// The present mass function's slope.
    pub mass_function_slope: f64,
    /// Central escape speed, km/s.
    pub escape_speed: f64,
}

impl CatalogueGlobular {
    /// The galactocentric radius, kpc.
    #[must_use]
    pub fn radius_kpc(&self) -> f64 {
        let [x, y, z] = self.position_kpc;
        (x * x + y * y + z * z).sqrt()
    }
}

/// The Baumgardt–Hilker catalogue's clusters (module documentation), in its order.
#[must_use]
pub fn milky_way_globulars() -> &'static [CatalogueGlobular] {
    &GLOBULARS
}

/// A named cluster of [`milky_way_globulars`]: 47 Tucanae (`NGC_104`), M4 (`NGC_6121`), Palomar 5
/// (`Pal_5`), ω Centauri (`NGC_5139`), M15 (`NGC_7078`), or any other by its catalogue name.
///
/// # Panics
///
/// If the catalogue has no cluster of that name.
#[must_use]
pub fn named_cluster(name: &str) -> &'static CatalogueGlobular {
    GLOBULARS
        .iter()
        .find(|g| g.name == name)
        .unwrap_or_else(|| panic!("the catalogue has no cluster {name}"))
}

