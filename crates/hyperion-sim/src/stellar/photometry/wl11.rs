/// The numerator of θ, K.
const THETA_K: f64 = 5_040.0;

/// BC<sub>V</sub> (mag, on the table's zero point) at `teff_k` (finite and positive) and `log_g`
/// (cm s⁻², finite), by the [module](self)'s interpolation: a row's own value at its temperature
/// and gravity.
#[must_use]
pub(super) fn bc_v_at(teff_k: f64, log_g: f64) -> f64 {
    let gravity = log_g.clamp(LOG_G[0], LOG_G[LOG_G.len() - 1]);
    let above = LOG_G
        .partition_point(|&x| x < gravity)
        .clamp(1, LOG_G.len() - 1);
    let in_g = (gravity - LOG_G[above - 1]) / (LOG_G[above] - LOG_G[above - 1]);
    let (low, high) = (&ROWS[above - 1], &ROWS[above]);
    let row = |i: usize| {
        let ((t0, bc0), (t1, bc1)) = (low[i], high[i]);
        (
            (1.0 - in_g) * (THETA_K / t0) + in_g * (THETA_K / t1),
            (1.0 - in_g) * bc0 + in_g * bc1,
        )
    };
    let theta = THETA_K / teff_k;
    // The first row at or past θ (θ rises down the rows), within 1..n so that the segment before
    // it is the first or the last beyond the table's ends.
    let (mut i, mut end) = (1, low.len() - 1);
    while i < end {
        let mid = i + (end - i) / 2;
        if row(mid).0 < theta {
            i = mid + 1;
        } else {
            end = mid;
        }
    }
    let ((theta_a, bc_a), (theta_b, bc_b)) = (row(i - 1), row(i));
    let f = (theta - theta_a) / (theta_b - theta_a);
    (1.0 - f) * bc_a + f * bc_b
}

#[cfg(test)]
mod tests {
    use hyperion_testkit::float::bits;

    use super::*;

    /// FNV-1a over every value's bits in order, so that an accidental edit of any digit fails.
    fn checksum(values: impl IntoIterator<Item = f64>) -> u64 {
        let mut hash = 0xcbf2_9ce4_8422_2325_u64;
        for value in values {
            for byte in bits(value).to_le_bytes() {
                hash = (hash ^ u64::from(byte)).wrapping_mul(0x0100_0000_01b3);
            }
        }
        hash
    }

    #[test]
    fn the_table_is_pinned_by_its_checksum() {
        let values = LOG_G
            .into_iter()
            .chain(V_MINUS_K)
            .chain(ROWS.into_iter().flatten().flat_map(|(t, bc)| [t, bc]));
        assert_eq!(checksum(values), TABLE_CHECKSUM);
    }

    const TABLE_CHECKSUM: u64 = 16_660_092_568_774_786_774;

    /// V − K runs from 1.1 by 0.1 to 5.0 and by 0.4 to 10.2, as in the source, and down every
    /// gravity's rows the temperature falls and the correction with it.
    #[test]
    fn temperature_and_correction_fall_down_every_gravity() {
        for pair in V_MINUS_K.windows(2) {
            let step = pair[1] - pair[0];
            let expected = if pair[1] <= 5.0 + 1e-9 { 0.1 } else { 0.4 };
            assert!((step - expected).abs() < 1e-9, "{pair:?}");
        }
        for rows in &ROWS {
            for pair in rows.windows(2) {
                assert!(pair[0].0 > pair[1].0, "{pair:?}");
                assert!(pair[0].1 > pair[1].1, "{pair:?}");
            }
        }
    }

    /// At a row's temperature and gravity the interpolation gives the row's correction exactly,
    /// and midway between two gravities the rows' mean at a V − K.
    #[test]
    fn the_rows_are_reproduced_exactly() {
        for (k, rows) in ROWS.iter().enumerate() {
            for &(t, bc) in rows {
                assert_eq!(bits(bc_v_at(t, LOG_G[k])), bits(bc), "{t} K, {}", LOG_G[k]);
            }
        }
        let ((t0, bc0), (t1, bc1)) = (ROWS[2][30], ROWS[3][30]);
        let theta = 0.5 * (THETA_K / t0) + 0.5 * (THETA_K / t1);
        let mid = bc_v_at(THETA_K / theta, 1.25);
        assert!((mid - f64::midpoint(bc0, bc1)).abs() < 1e-12, "{mid}");
    }
}
