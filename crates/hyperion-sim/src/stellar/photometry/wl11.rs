//! The colour–temperature calibration of Worthey and Lee (2011, ApJS 193, 1) at solar abundance:
//! effective temperature and the V-band bolometric correction along its grid of V − K, at every
//! gravity from log g 0.0 to 5.5 (plan 06, P06.T43.a, rendering plan R06's ask A4).
//!
//! **Source and version.** The authors' table `mash2.out` of 2010-09-15, in "Color Calibration
//! Table and Interpolation Program" (`colorinterp.tar.gz`, SHA-256
//! `763ef82176cfeff29edd0a8718f0171c13655697f51b494d74b8cac385c643f2`; the table's
//! `050d07ffd2b95033df37566ff6f6e480f7154dc1e52281a2d0ce1af6c1413424`) at
//! <http://astro.wsu.edu/models/>, as the Internet Archive keeps it, since the site could not be
//! reached when this was built (2026-10-28); the authors state no terms beyond offering the table
//! and program (their section 4). Each of its rows gives [Fe/H], log g, T<sub>eff</sub>,
//! seven colours and BC<sub>V</sub> at one of 75 values of V − K (−1.06 to 10.2) for 7 abundances
//! ([Fe/H] −2.5 to +0.5) and 13 gravities (log g −0.5 to 5.5). Kept here: the rows of [Fe/H] = 0
//! at the 12 gravities from 0.0 to 5.5 and from V − K = 1.1 (6,229–6,625 K) to the table's red
//! end, which hold every temperature the giants' correction reads (6,000 K and below),
//! T<sub>eff</sub> and BC<sub>V</sub> as printed. The log g −0.5 rows are left out: below log g
//! 0.0 the photometry reads Levesque et al.'s supergiants' column over this table's log g 0.0.
//!
//! **What the table is.** Johnson–Cousins photometry of stars of known [Fe/H] fitted as
//! colour–colour relations in gravity and abundance, with literature temperature and
//! bolometric-correction scales attached (their sections 2 and 2.5): VandenBerg and Clem's (2003)
//! corrections in the middle of the temperature range and, at the cool end, Bessell, Castelli and
//! Plez's (1998) average K-band correction for giants and Leggett et al.'s (2001) for cool dwarfs.
//! For cool stars the correction is a function of colour alone, so that "gravity and abundance
//! dependence then is inherited from the gravity and abundance variations of the color-color
//! diagrams". Its zero point is VandenBerg and Clem's, BC<sub>V</sub>☉ = −0.09 (section 2.5).
//!
//! **Interpolation.** As the authors' program `mash3.f` (`teffinterp`) combines gravities: linear
//! in log g between the two about the star at each V − K, for θ = 5,040 K ÷ T<sub>eff</sub> and
//! BC<sub>V</sub> alike, with log g held at 0.0 below the rows kept and at 5.5 above them (our
//! choice: the program extrapolates in log g, and has a −0.5 row); then along the
//! rows in θ, linearly where the program fits a five-point polynomial, so that a correction lies
//! between its rows as the dwarf table's do; and beyond the coolest row linearly in θ from the last
//! two, as the program extrapolates.

