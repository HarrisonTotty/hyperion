    #[test]
    fn the_columns_agree_at_every_node() {
        assert!(TEFF_K.windows(2).all(|pair| pair[0] < pair[1]));
        assert!(LOG_G.windows(2).all(|pair| pair[0] < pair[1]));
        for (k, row) in M_BOL_AND_V.iter().enumerate() {
            for (j, &(m_bol, v)) in row.iter().enumerate() {
                let rounding = (v - (m_bol - BC_V[k][j])).abs();
                assert!(
                    rounding <= 0.001 + 1e-9,
                    "{} K, {}: {rounding}",
                    TEFF_K[j],
                    LOG_G[k]
                );
            }
        }
    }
