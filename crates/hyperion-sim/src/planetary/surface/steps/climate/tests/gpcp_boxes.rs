//! GPCP v2.3's monthly precipitation climatology over 1991–2020 on Earth's land boxes (R09.T13.l):
//! the observed side of the geographic model's comparison with observed climatologies
//! ([`climatology`](super::climatology)). A land box is one of the climate model's 2.5° × 5° boxes
//! whose Natural Earth land share is at least half ([`EARTH_LAND_BOXES`](super::EARTH_LAND_BOXES)
//! at 500 thousandths or more): 1,713 of the 5,184. Test data, not shipped (`NOTICE`, "Test data
//! (not shipped)"). GPCP's papers: Adler, R. F., et al. 2003, J. Hydrometeor. 4, 1147–1167 (version
//! 2), and Adler, R. F., et al. 2018, Atmosphere 9, 138, doi:10.3390/atmos9040138 (version 2.3).
//!
//! # The inputs
//!
//! NOAA NCEI's GPCP Monthly Climate Data Record, version 2.3 (`v02r03`), as NOAA's Open Data
//! Dissemination programme (NODD) distributes it on AWS (the bucket
//! `noaa-cdr-precip-gpcp-monthly-pds`, `data/<year>/`): the 360 monthly files of January 1991 to
//! December 2020, each month's final file (`gpcp_v02r03_monthly_d<yyyymm>_c<date>.nc`; where a
//! preliminary file was also published, the final one supersedes it). Their `sha256sum` listing in
//! name order (`sha256sum *.nc`) has SHA-256
//! `91455635ac673233aa4e5a6754439a369f8509661a31085c8e0a846bb802322a`. Its terms: each file's
//! `license` attribute reads "No constraints on data access or use", and NODD's are that its data
//! "are open to the public and can be used as desired", NOAA requesting attribution and no implied
//! endorsement. NOAA PSL's distribution, which [`hydrology`](super::hydrology)'s annual zonal table
//! read (`precip.mon.ltm.1991-2020.nc`), could not be reached from the lane's machine; it is the
//! same record (below).
//!
//! # The method
//!
//! - Each calendar month's mean over the 30 years of each 2.5° cell's `precip`, mm/day (every value
//!   lies in the variable's valid range, 0 to 100; none is missing).
//! - A box's value: the mean of the two 2.5° cells it spans, which share its latitudes exactly and
//!   are of equal area.
//! - Printed in hundredths of a mm/day (the record's float32 values carry about 10⁻⁶ mm/day).
//! - The check: the same climatology's annual zonal means (months weighted by their days, February
//!   28.25) are [`hydrology`](super::hydrology)'s `GPCP_ANNUAL_MM_PER_DAY`, from PSL's long-term
//!   means, in all 72 bands to the printed 0.01 mm/day, and its global mean is 2.691 mm/day, as
//!   there.
//!
//! The lane's scripts (`gpcp_fetch.py`, `climatology.py` and `emit_tables.py`) are in its outbox,
//! not the repository.

