//! NCEP/NCAR Reanalysis 1's monthly zonal-mean 2 m air temperature over 1991–2020, reduced to the
//! sea level over land, on the climate model's 72 bands of 2.5° (decision-r09-t13i §3.4, 1): the
//! test data of the partition's test on observed temperatures
//! ([`the_partition_on_observed_temperatures_converges_on_the_storm_tracks_every_month`](super::observed)).
//! Test data, not shipped (`NOTICE`, "Test data (not shipped)"). NOAA PSL's data are in the public
//! domain. The dataset's citation: E. Kalnay et al. 1996, "The NCEP/NCAR 40-Year Reanalysis
//! Project", Bull. Amer. Meteor. Soc. 77, 437–471.
//!
//! # The inputs
//!
//! NOAA PSL's `OPeNDAP` ASCII responses (decision-r09-t13e-revision's downloads, which
//! decision-r09-t13i's prototype read), each named by the dataset path its header prints:
//!
//! - `Datasets/ncep.reanalysis/Monthlies/surface_gauss/air.2m.mon.ltm.1991-2020.nc`, `air`, the
//!   long-term monthly means on the T62 Gaussian grid (94 × 192), K: SHA-256
//!   `b9a2975a9f86374f367d36ec0290764115e0b99c1e70218b0ce1d432d4b2be75`;
//! - `Datasets/ncep.reanalysis/surface_gauss/land.sfc.gauss.nc`, `land`, the land mask on the same
//!   grid: SHA-256 `e0ed482fac510a56fc7e8f283716571fb5d02aec039bff64857e836467de7002`;
//! - `Datasets/ncep.reanalysis/surface/hgt.sfc.nc`, `hgt`, the surface height on the 2.5° grid
//!   (73 × 144), m: SHA-256 `143288110477b46e2e6565edf33f1ec7e5d4bc0c638f7be0bd479a6c9c0d3623`.
//!
//! # The method (the ruling's `obs_weighting.py`, its "zonal" variant, exactly)
//!
//! - Each Gaussian row of latitude φ goes to band min(71, ⌊(φ + 90°) ÷ 2.5°⌋).
//! - Each point's temperature, plus Γ max(0, z) where the land mask exceeds 0.5, with Γ the
//!   reference Earth's lapse rate, 5.829 K km⁻¹ (`lapse::lapse_rate_k_per_m`, 0.6 g ÷ `c_p`; the
//!   test checks it), and z the 2.5° grid's height at the row nearest the point's latitude (the
//!   first of ties) and the column round(λ ÷ 2.5°) mod 144 (Python's `round`, ties to even), λ =
//!   1.875° i.
//! - Each band's mean over all of its points, land and sea, weighted by the cosine of each row's
//!   latitude. Every band holds at least one row, so no band is filled from a neighbour.
//! - Printed to 0.001 K (the release's float32 values carry about 10⁻⁵ K).
//!
//! The lane's script is `ncep_bands.py` in its scratch (`r09-water/scripts/`), run with the inputs
//! above and Γ = 5.829 × 10⁻³ K m⁻¹.
//!
//! The table was re-run at version 23's reference Earth (P14.T54.a), whose Γ the batch moved from
//! R09.T13.i's 5.818 K km⁻¹: its `c_p` became P14.T49.b's `c_p`(T) at the mean surface
//! temperature, and its water vapour 0.77 of the saturation pressure, P14.T51.a's partition's
//! convention, in place of the whole (`reference::earth_air`). The script reproduced R09.T13.i's
//! table exactly at 5.818 × 10⁻³ before the re-run; the new Γ moves the band means by at most
//! 0.030 K, over Antarctica's heights.

