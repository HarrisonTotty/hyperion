/// The tables' guard (decision-r09-t13e-asbuilt §1.6): each band's mean over its columns of
/// [`EARTH_LAND_BOXES`] is its [`EARTH_LAND_SHARE`] within 1.0 × 10⁻⁴ (8.3 × 10⁻⁵ at worst,
/// 68.75° N: the boxes' rounding to thousandths, the two tables one computation's), no box's share
/// exceeds 1000, and a band with no land has no box land. The realised shares of the synthetic
/// sea's cells are checked at level 7 by `era_earth`, within 0.03.
#[test]
fn earth_s_land_by_box_averages_to_its_land_share_by_band() {
    let columns = index(GEOGRAPHIC_COLUMNS);
    let mut worst: f64 = 0.0;
    for (band, (row, &share)) in EARTH_LAND_BOXES.iter().zip(&EARTH_LAND_SHARE).enumerate() {
        assert!(row.iter().all(|&m| m <= 1_000), "band {band}: {row:?}");
        if share <= 0.0 {
            assert!(row.iter().all(|&m| m == 0), "band {band}: {row:?}");
        }
        let mean = row.iter().fold(0.0, |sum, &m| sum + f64::from(m)) / (1_000.0 * columns);
        assert!(
            (mean - share).abs() <= 1.0e-4,
            "band {band}: {mean} against {share}"
        );
        worst = worst.max((mean - share).abs());
    }
    eprintln!("the boxes' band means against EARTH_LAND_SHARE: {worst:.2e} at worst");
}
