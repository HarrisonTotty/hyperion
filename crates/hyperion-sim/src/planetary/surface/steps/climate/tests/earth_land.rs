//! Earth's land for the climate step's tests, as test-only data (R09.T13.a, R09.T13.g and
//! R09.T13.e; decision-r09-t13e-asbuilt §1.6): its share by 2.5° band and by 2.5° × 5° box from
//! Natural Earth, and its hypsometry by band and each box's median land height from Earth2014,
//! which [`synthetic_sea`](super::synthetic_sea) lays out; and the tables' guard. The module is
//! compiled only under the climate step's tests, so none of it reaches the sim.
//!
//! # The sources and the method
//!
//! - **Natural Earth's 1:110m land polygons** (public domain, naturalearthdata.com, "Made with
//!   Natural Earth"): `ne_110m_land.geojson`, SHA-256
//!   `9e0729ee253ca7d7a5c4ae9395fb1902264c5377c52e224d13dd85010e2835d9` (its release not
//!   recorded). Even–odd scanlines in longitude and latitude, 40 to a 2.5° band, each weighted by
//!   the cosine of its latitude; a box's share is its band's scanlines' land clipped exactly to its
//!   5° column, so that a band's mean over its 72 columns is its share (the lanes' scratch
//!   `land_bands.py` and `e/landmask/land_boxes.py`). Only the derived shares are committed; no
//!   polygon is.
//! - **Earth2014** (C. Hirt and M. Rexer 2015, Int. J. Appl. Earth Obs. Geoinf. 39, 103–112, DOI
//!   10.1016/j.jag.2015.03.001, its readme read; ddfe.curtin.edu.au/models/Earth2014/), its 5′
//!   grids: the physical surface `Earth2014.SUR2014.5min.geod.bin`, SHA-256
//!   `6e07fef563b6ad9db8e040cbad523008883682441db47e244dbce7f6157b7a75`, and for the land mask only
//!   the ice thickness `Earth2014.ICE2014.5min.geod.bin`
//!   (`eb60f2590c75a3d6aab7f33138e71e73442069b71f0eb6df81a0030711f17907`), the bedrock
//!   `Earth2014.BED2014.5min.geod.bin`
//!   (`7997fe72e6d16aade237ba800655f756e7f69cce6e271f4679fc830b3cc8c08b`) and the Earth without its
//!   water, `Earth2014.TBI2014.5min.geod.bin`
//!   (`e6b360af9ed471c4b6feff38ed72540e4d00e4e6e332d8fb9422d5cad1d8f91e`). Each is 16-bit
//!   big-endian integers, metres above mean sea level, in 2,160 cell-centred rows from the south by
//!   4,320 columns from −180°. A 5′ cell is land unless it is ocean (SUR 0, TBI below 0, no ice), a
//!   floating ice shelf (ice over a water column, TBI − ICE − BED, of at least 2 m, its surface
//!   under 1,000 m, so that Lake Vostok stays land) or the Caspian (a lake cell, SUR at least 1 m
//!   above TBI with no ice, within 36–48° N and 46–55.5° E: Natural Earth's one land hole at
//!   1:110m). A lake is land at its surface, as Natural Earth's land holds it. Each 5′ row is
//!   weighted by the cosine of its latitude (the lane's scratch `g/scripts/hypsometry.py`, and
//!   `g/boxmedian/box_median.py`, which reads and masks the grids by the same code). Only the
//!   derived statistics are committed; no grid is (decision-r09-t13ge §1.5; `NOTICE`, "Test data
//!   (not shipped)").

